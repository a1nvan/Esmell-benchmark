"""Reproduce the retrospective E6 protocol comparison (Table E6 protocols).

Uses the original 160-tree ExtraTrees regressor from multi_label_exp.ipynb,
but restricts the records to the frozen E5/E6 cohort. The canonical signal
cache must first be generated by experiment 05 or 06 from the raw archives.

No results from the later period are used for model fitting, preprocessing,
or selection. The grouped-day comparison is retrospective, not chronological.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re

import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import ExtraTreesRegressor
from sklearn.model_selection import GroupKFold

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
GASES = ("acetone", "isopropanol", "pentane")
CHANNELS = ("R1", "R2", "R11", "R12", "R16", "R17")
STEMS = {130: "curiosity-2v15.130.0", 146: "curiosity-2v15.146.0"}
PROFILE = "DefaultCSV+Simplify+SelectR+Cycles+CoolHeat3eps.2+CanonicalTempAlign200(175,390)+Subtraction1,-3,5"
RECIPE = re.compile(r"(acetone|isopropanol|pentane)\[([0-9]+(?:\.[0-9]+)?)ppb\]")
SEED = 42
# Reference numbers are used only for a final consistency assertion.
REFERENCE = {
    "day_grouped_cv": (0.291, 0.224),
    "next_day_130": (0.181, 0.324),
    "later_campaign_146": (0.302, 0.376),
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(4 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def cache_signature(archive_hashes: dict[int, str], windows_paths: bool) -> str:
    hashes = {}
    for path in (SRC / "esdata").rglob("*.py"):
        relative = path.relative_to(SRC).as_posix()
        hashes[relative.replace("/", "\\") if windows_paths else relative] = sha256(path)
    assert len(hashes) == 15, "Unexpected source layout in src/esdata"
    payload = dict(archive_hashes=archive_hashes, code_hashes=hashes,
                   channels=CHANNELS, profile=PROFILE)
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


def load_signals(cache_path: Path, data_dir: Path):
    manifest = {}
    for line in (ROOT / "data" / "archive_checksums.sha256").read_text().splitlines():
        if line.strip():
            digest, name = line.split(None, 1)
            manifest[name.strip()] = digest
    archives, hashes = {}, {}
    for card, stem in STEMS.items():
        found = list(data_dir.glob(stem + ".tar*.gz"))
        if len(found) != 1:
            raise FileNotFoundError(f"Expected exactly one archive {stem} in {data_dir}")
        archives[card] = found[0]
        hashes[card] = sha256(found[0])
        if hashes[card] != manifest[stem + ".tar.gz"]:
            raise ValueError(f"Raw archive checksum mismatch: {found[0].name}")
    valid_signatures = {cache_signature(hashes, windows_paths=False),
                        cache_signature(hashes, windows_paths=True)}
    with np.load(cache_path, allow_pickle=False) as item:
        recorded = str(item["signature"].item())
        if recorded not in valid_signatures:
            raise ValueError("Signal cache does not match the raw archives or src/esdata source")
        metadata = pd.read_json(io.StringIO(str(item["metadata_json"].item())),
                                orient="records")
        signals = item["X"].astype(np.float32)
    metadata["time"] = pd.to_datetime(metadata.time)
    samples = (metadata[metadata.split.ne("excluded")]
               .sort_values(["card", "time"]).reset_index(drop=True))
    if signals.shape != (3477, 12, 200) or len(samples) != len(signals):
        raise ValueError("Unexpected signal cache shape/metadata alignment")
    if samples[["card", "sample_id"]].duplicated().any() or not np.isfinite(signals).all():
        raise ValueError("Duplicate sample identifier or non-finite signal")
    return samples, signals, recorded, hashes


def concentrations(labels: pd.Series) -> np.ndarray:
    out = np.full((len(labels), 3), np.nan)
    for i, label in enumerate(labels):
        if label == "air":
            continue
        parts = label.lower().split("+")
        for part in parts:
            match = RECIPE.fullmatch(part)
            if not match:
                raise ValueError(f"Invalid nominal recipe: {label}")
            col = GASES.index(match[1])
            if np.isfinite(out[i, col]):
                raise ValueError(f"Repeated gas in nominal recipe: {label}")
            out[i, col] = float(match[2])
    return out


def kinetics192(signals: np.ndarray) -> np.ndarray:
    """Feature ordering is identical to multi_label_exp.ipynb, cell 8."""
    x = signals.astype(np.float64)
    statistics = np.concatenate([x.mean(2), x.std(2), x.min(2), x.max(2),
                                 np.median(x, axis=2),
                                 np.percentile(np.abs(x), 90, axis=2)], axis=1)
    bins = np.stack([piece.mean(2) for piece in np.array_split(x, 10, axis=2)],
                    axis=2).reshape(len(x), -1)
    features = np.concatenate((statistics, bins), axis=1).astype(np.float32)
    assert features.shape == (len(x), 192)
    return features


def weighted_median(values: np.ndarray, weights: np.ndarray) -> float:
    order = np.argsort(values)
    v, w = values[order], weights[order]
    return float(v[np.searchsorted(np.cumsum(w), 0.5 * w.sum())])


def fit_predict(train, test, features, truth_log, present, cardinality, seed):
    """Both the constant baseline and the old regressor fit on train only."""
    median_pred = np.full((len(test), 3), np.nan)
    tree_pred = np.full((len(test), 3), np.nan)
    for gas in range(3):
        positive = train[present[train, gas]]
        pure = cardinality[positive] == 1
        mixed = ~pure
        if not pure.any() or not mixed.any():
            raise ValueError("Calibration split must contain pure and mixed records")
        weights = np.where(pure, .5 / pure.sum(), .5 / mixed.sum())
        median_pred[:, gas] = weighted_median(truth_log[positive, gas], weights)
        regressor = ExtraTreesRegressor(n_estimators=160, min_samples_leaf=4,
                                       max_features=0.85, n_jobs=-1,
                                       random_state=seed + 100 * gas)
        regressor.fit(features[positive], truth_log[positive, gas])
        tree_pred[:, gas] = regressor.predict(features[test])
    return median_pred, tree_pred


def score(test, pred, truth, present, cardinality, protocol, model, fold):
    per_group, long_rows = [], []
    for gas, name in enumerate(GASES):
        for kind, select in (("pure", cardinality[test] == 1),
                             ("mixture", cardinality[test] >= 2)):
            indices = np.flatnonzero(present[test, gas] & select)
            if len(indices):
                mae = float(np.abs(pred[indices, gas] - truth[test[indices], gas]).mean())
                per_group.append(dict(protocol=protocol, model=model, fold=fold,
                                      gas=name, kind=kind, n=len(indices), log_mae=mae))
        for local in np.flatnonzero(present[test, gas]):
            long_rows.append(dict(index=int(test[local]), protocol=protocol,
                                  fold=fold, model=model, gas=name,
                                  actual_log=float(truth[test[local], gas]),
                                  predicted_log=float(pred[local, gas])))
    return per_group, long_rows


def run(samples, x):
    concentration = concentrations(samples.recipe)
    present = np.isfinite(concentration)
    card = samples.card.to_numpy()
    days = samples.time.dt.strftime("%Y-%m-%d").to_numpy()
    cardinality = present.sum(axis=1)
    truth_log = np.log10(np.where(present, concentration, 1.0))
    features = kinetics192(x)
    train = np.flatnonzero((card == 130) & (days < "2026-09-28"))
    following_day = np.flatnonzero((card == 130) & (days == "2026-09-28"))
    followup = np.flatnonzero(card == 146)
    full_130 = np.sort(np.concatenate((train, following_day)))
    assert (len(train), len(following_day), len(followup), len(full_130)) == (2409, 152, 916, 2561)
    assert np.intersect1d(train, following_day).size == 0
    assert np.intersect1d(train, followup).size == 0
    assert samples.time.iloc[train].max() < samples.time.iloc[following_day].min()

    results, details, predictions = [], [], []
    protocols = [
        ("day_grouped_cv", [(full_130[a], full_130[b], SEED + fold)
                             for fold, (a, b) in enumerate(
                                 GroupKFold(n_splits=3).split(
                                     full_130, groups=days[full_130]), start=1)]),
        ("next_day_130", [(train, following_day, SEED)]),
        ("later_campaign_146", [(train, followup, SEED)]),
    ]
    for name, folds in protocols:
        held_out = np.concatenate([test for _, test, _ in folds])
        if name == "day_grouped_cv":
            assert len(np.unique(held_out)) == 2561
            assert all(not set(days[tr]).intersection(days[te]) for tr, te, _ in folds)
        oof = {key: np.full((len(samples), 3), np.nan)
               for key in ("GasMedian", "ExtraTrees")}
        for fold_number, (tr, te, seed) in enumerate(folds, start=1):
            median, forest = fit_predict(tr, te, features, truth_log, present, cardinality, seed)
            for model, prediction in (("GasMedian", median), ("ExtraTrees", forest)):
                oof[model][te] = prediction
                _, rows = score(te, prediction, truth_log, present,
                                cardinality, name, model, fold_number)
                predictions.extend(rows)
        for model, pred in oof.items():
            per_group, _ = score(held_out, pred[held_out], truth_log, present,
                                 cardinality, name, model, fold="pooled")
            if len(per_group) != 6:
                raise AssertionError(f"Incomplete gas x exposure-type cells: {name}")
            # CV macro-6 is scored over pooled out-of-fold predictions, NOT
            # as the mean of per-fold scores (one fold lacks mixtures).
            value = float(np.mean([row["log_mae"] for row in per_group]))
            results.append(dict(protocol=name, model=model, macro6_log_mae=value,
                                n_records=len(held_out), n_mixtures=int((cardinality[held_out] >= 2).sum()),
                                n_test_days=len(set(days[held_out]))))
            details.extend(per_group)
    return pd.DataFrame(results), pd.DataFrame(details), pd.DataFrame(predictions)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path,
                        default=Path(os.environ.get("ESMELL_DATA_DIR", ROOT / "data" / "raw")))
    parser.add_argument("--cache", type=Path, help="Verified E5/E6 signals_cache.npz")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "outputs" / "E6_retrospective")
    parser.add_argument("--no-reference-check", action="store_true",
                        help="Export a descriptive run even if it differs from manuscript values")
    args = parser.parse_args()
    choices = ([args.cache] if args.cache else [
        SRC / "outputs" / "E6_concentration_v1" / "signals_cache.npz",
        SRC / "outputs" / "E5_diagnostic_v2" / "signals_cache.npz",
        SRC / "outputs" / "E7_end_to_end_v1" / "signals_cache.npz",
    ])
    cache = next((p for p in choices if p is not None and p.is_file()), None)
    if cache is None:
        raise FileNotFoundError("No signal cache found. Run notebook 05 or 06 on raw data first, "
                                "then rerun this script (or supply --cache PATH).")
    samples, signals, signature, archive_hashes = load_signals(cache, args.data_dir)
    main_scores, detail, predictions = run(samples, signals)
    wide = main_scores.pivot(index="protocol", columns="model", values="macro6_log_mae")
    wide = wide.loc[list(REFERENCE)]
    print("\nRetrospective E6: macro-six log10(ppb) MAE (lower is better)")
    print(wide.to_string(float_format=lambda n: f"{n:.6f}"))
    if not args.no_reference_check:
        for protocol, (median, forest) in REFERENCE.items():
            if round(float(wide.loc[protocol, "GasMedian"]), 3) != median:
                raise AssertionError(f"Baseline does not reproduce paper: {protocol}")
            if round(float(wide.loc[protocol, "ExtraTrees"]), 3) != forest:
                raise AssertionError(f"ExtraTrees does not reproduce paper: {protocol}")
        print("PASS: all six reported values reproduced at three decimals")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    wide.reset_index().to_csv(args.output_dir / "protocol_scores.csv", index=False)
    detail.to_csv(args.output_dir / "by_gas_and_type.csv", index=False)
    predictions["sample_id"] = samples.sample_id.iloc[predictions["index"].to_numpy()].to_numpy()
    predictions.to_csv(args.output_dir / "predictions.csv", index=False)
    metadata = dict(model="ExtraTrees (original multi_label_exp configuration)",
                    seed=SEED, trees=160, leaf_size=4, max_features=0.85,
                    no_presence_bits_as_features=True, no_output_clipping=True,
                    cv="GroupKFold(3) on 14 days of card 130, pooled out-of-fold macro-six",
                    forward_training="card 130 through 27 September; no validation refit",
                    expected_archive_sha256=archive_hashes,
                    cache_signature=signature, sklearn_version=sklearn.__version__,
                    observed_records=3477, literature_status="retrospective, not confirmatory")
    (args.output_dir / "run_config.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(f"Saved: {args.output_dir}")


if __name__ == "__main__":
    main()
